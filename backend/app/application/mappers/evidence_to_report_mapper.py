def _build_founder_cards(
    evidence: Evidence, founder_names: list[str], company_name: str = "",
) -> list[dict[str, Any]]:
    """Build founder card dicts matching the existing FounderCard shape."""
    cards: list[dict[str, Any]] = []

    profile_map: dict[str, PersonProfile] = {}
    for p in evidence.founder_profiles:
        if p.name:
            profile_map[p.name.lower()] = p

    for name in founder_names:
        profile = _find_profile(name, profile_map)

        lines: list[list[str]] = []
        fit = ""

        if profile:
            edu_parts = [
                f"{e.get('degree', '')} — {e.get('institution', '')} ({e.get('year', '')})"
                for e in profile.education
                if e.get("institution")
            ]
            if edu_parts:
                lines.append(["Education", "; ".join(edu_parts)])

            exp_parts = [
                f"{e.get('title', '')} at {e.get('company', '')} ({e.get('duration', '')})"
                for e in profile.experience
                if e.get("company")
            ]
            if exp_parts:
                lines.append(["Experience", "; ".join(exp_parts)])
            elif profile.headline:
                lines.append(["Current role", profile.headline])

            if profile.summary:
                fit = profile.summary[:300]
            elif profile.headline:
                fit = f"{name}'s background as {profile.headline} is relevant to {name}'s role."

            p_url = getattr(profile, "url", None) or getattr(profile, "source_url", None)
            if p_url and p_url.startswith("manual:"):
                source_cite = "Provided by user (unverified)"
                if not profile.headline or profile.headline == "provided by user (unverified)":
                    role = "Founder (provided by user)"
                else:
                    role = profile.headline
                lines.append(["Role source", source_cite])
                lines.append(["Background status", "Provided by user (unverified)"])
            else:
                if profile.headline:
                    role = profile.headline
                else:
                    role = "Founder (evidenced via LinkedIn)"
                source_cite = f"LinkedIn profile ({p_url})" if p_url else "LinkedIn profile"
                lines.append(["Role source", source_cite])
        else:
            # 1. Rules-based extraction from website team/about pages
            team_info = _extract_founder_from_team_pages(name, evidence.website_pages)

            if team_info:
                role = team_info["role"]
                page_url = team_info["url"]
                quote = team_info["quote"]
                lines.append(["Role", role])
                source_cite = f"Company website: {page_url}" if page_url else "Company website"
                lines.append(["Role source", source_cite])
                lines.append(["Supporting quote", quote.replace("\n", " — ")])
                lines.append(["Background status", "Operating role verified from official website; academic credentials and employment history unverified from public sources and flagged under Information to prepare."])
                fit = f"{name} is verified on {company_name or 'the company'} official website ({page_url}) as {role}."
            else:
                snippet_mention = getattr(evidence, "search_snippets", {}).get(f"founder_{_slugify(name)}")
                if snippet_mention:
                    lines.append(["Search excerpt", snippet_mention[:200]])
                    lines.append(["Role source", "Public web search snippet"])
                    lines.append(["Background status", "Referenced in web search snippet; education and prior career history unverified from public sources and flagged under Information to prepare."])
                    fit = f"{name} is referenced in public web search results."
                    role = "Founder (from search snippet)"
                else:
                    lines.append(["Role source", "Provided by user (unverified)"])
                    lines.append(["Background status", "Named in screening request; education and prior operating experience unverified from public sources; flagged as an actionable diligence request under Information to prepare."])
                    fit = "Founder named in screening request; public background could not be corroborated from public sources and is flagged under Information to prepare."
                    role = "Founder (provided by user)"

        cards.append({
            "name": name,
            "role": role,
            "lines": lines,
            "fit": fit,
        })

    return cards


def _find_profile(name: str, profile_map: dict[str, PersonProfile]) -> PersonProfile | None:
    """Fuzzy match a founder name to a scraped profile."""
    name_lower = name.lower()
    # Exact match
    if name_lower in profile_map:
        return profile_map[name_lower]
    # Partial match (last name)
    parts = name_lower.split()
    for key, profile in profile_map.items():
        if any(part in key for part in parts if len(part) > 2):
            return profile
    return None


