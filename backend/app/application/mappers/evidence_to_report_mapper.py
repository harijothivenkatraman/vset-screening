_BOILERPLATE_REGEX = re.compile(
    r"\b(?:online now|expert is available|talk to us|chat with us|leave a message|"
    r"we're online|we are online|how can we help|typically replies|reply time|agents? online|"
    r"accept all cookies|cookie policy|we use cookies|privacy policy|terms of service|"
    r"manage preferences|all rights reserved|oops! something went wrong|"
    r"submitting the form|submission has been received)\b",
    re.I,
)


def _is_boilerplate(text: str | None) -> bool:
    if not text:
        return True
    return _BOILERPLATE_REGEX.search(text) is not None


def _extract_merged_company_overview(evidence: Evidence, company_name: str) -> str:
    """Extract company overview description from LinkedIn, website, or search snippets."""
    cp = evidence.company_profile
    if cp and cp.description and len(cp.description.strip()) > 10 and not _is_boilerplate(cp.description):
        return cp.description.strip()

    # Try website pages: JSON-LD description -> meta/OG description -> clean body text
    about_text = _extract_about_from_pages(evidence.website_pages)
    if about_text:
        return about_text

    # Try search snippets
    snippets = getattr(evidence, "search_snippets", {})
    if "company" in snippets and snippets["company"]:
        return snippets["company"].strip()

    return NOT_ESTABLISHED


def _extract_about_from_pages(pages: list[Any]) -> str | None:
    """Extract narrative about/company text from website pages."""
    # 1. Prefer JSON-LD description from Organization/Corporation/LocalBusiness
    for page in pages:
        for item in getattr(page, "json_ld", []):
            if isinstance(item, dict) and item.get("@type") in ("Organization", "Corporation", "LocalBusiness"):
                desc = item.get("description")
                if desc and isinstance(desc, str) and len(desc.strip()) > 15 and not _is_boilerplate(desc):
                    return desc.strip()

    # 2. Prefer page meta/OG description
    for page in pages:
        desc = getattr(page, "description", "")
        if desc and len(desc.strip()) > 15 and not _is_boilerplate(desc):
            return desc.strip()

    # 3. Prefer narrative lines from about/story/team/mission pages
    for page in pages:
        url_lower = getattr(page, "url", "").lower()
        title_lower = getattr(page, "title", "").lower()
        if any(k in url_lower or k in title_lower for k in ("about", "company", "story", "team", "mission")):
            text = getattr(page, "text", "")
            if text and len(text.strip()) > 30:
                valid_lines = [
                    l.strip() for l in text.strip().split("\n")
                    if len(l.strip()) > 25 and not _is_boilerplate(l)
                ]
                if valid_lines:
                    return " ".join(valid_lines[:4])[:600]

    # 4. Fallback to homepage clean body text
    if pages:
        first_page = pages[0]
        text = getattr(first_page, "text", "")
        if text and len(text.strip()) > 30:
            valid_lines = [
                l.strip() for l in text.strip().split("\n")
                if len(l.strip()) > 25 and not _is_boilerplate(l)
            ]
            if valid_lines:
                return " ".join(valid_lines[:3])[:500]

    return None


def _extract_year_simple(val: Any) -> str | None:
    """Extract a 4-digit year from string without importing infra."""
    if not val:
        return None
    import re
    match = re.search(r"\b(19\d\d|20\d\d)\b", str(val))
    return match.group(1) if match else None


def _extract_merged_company_profile(
    evidence: Evidence, company_name: str, website: str | None
) -> tuple[list[list[str]], dict[str, str]]:
    """Build company profile KV pairs and ribbon dictionary from merged evidence."""
    cp = evidence.company_profile
    pairs: list[list[str]] = [
        ["Legal name", company_name],
    ]
    ribbon: dict[str, str] = {}

    sector = None
    headquarters = None
    founded_year = None
    company_size = None
    specialties: list[str] = []

    # 1. From LinkedIn profile if available
    if cp:
        if cp.industry and cp.industry.lower() != "linkedin":
            sector = cp.industry
        if cp.headquarters:
            headquarters = cp.headquarters
        if cp.founded_year:
            founded_year = cp.founded_year
        if cp.company_size:
            company_size = cp.company_size
        if cp.specialties:
            specialties.extend(cp.specialties)

    # 2. From Website pages / JSON-LD
    for page in evidence.website_pages:
        for item in getattr(page, "json_ld", []):
            if isinstance(item, dict) and item.get("@type") in ("Organization", "Corporation", "LocalBusiness"):
                if not sector:
                    ka = item.get("knowsAbout")
                    if isinstance(ka, list) and ka:
                        sector = ", ".join(str(x) for x in ka[:3])
                    elif isinstance(ka, str) and ka:
                        sector = ka
                if not headquarters:
                    addr = item.get("address")
                    if isinstance(addr, dict):
                        parts = [addr.get("addressLocality"), addr.get("addressCountry")]
                        hq_str = ", ".join([str(p).strip() for p in parts if p and str(p).strip()])
                        if hq_str:
                            headquarters = hq_str
                    elif isinstance(addr, str) and addr.strip():
                        headquarters = addr.strip()
                if not founded_year and item.get("foundingDate"):
                    yr = _extract_year_simple(item.get("foundingDate"))
                    if yr:
                        founded_year = yr
                if not company_size and item.get("numberOfEmployees"):
                    num = item.get("numberOfEmployees")
                    if isinstance(num, dict):
                        company_size = str(num.get("name", "")).strip() or None
                    elif num:
                        company_size = str(num).strip()

    # 3. Fallback from website content / descriptions / text
    if not sector:
        all_web_text = " ".join([
            f"{getattr(p, 'title', '')} {getattr(p, 'description', '')} {getattr(p, 'text', '')[:300]}"
            for p in evidence.website_pages
        ]).lower()
        if any(kw in all_web_text for kw in ["fintech", "finance automation", "banking", "accounting", "accounts payable", "erp"]):
            sector = "Fintech"

    if not headquarters:
        for page in evidence.website_pages:
            t = f"{getattr(page, 'title', '')} {getattr(page, 'description', '')} {getattr(page, 'text', '')[:500]}".lower()
            if "india" in t:
                headquarters = "India"
                break

    # Extract Stage, Customer model, Target customers
    stage = None
    customer_model = None
    target_customers = None

    all_page_text = " ".join([
        f"{getattr(p, 'title', '')} {getattr(p, 'description', '')} {getattr(p, 'text', '')[:400]}"
        for p in evidence.website_pages
    ]).lower()
    all_news_text = " ".join([
        f"{getattr(a, 'title', '')} {getattr(a, 'text', '')[:300]}"
        for a in getattr(evidence, "news_articles", [])
    ]).lower()
    combined_signal = f"{all_page_text} {all_news_text}"

    if "pre-series a" in combined_signal or "pre series a" in combined_signal:
        stage = "Pre-Series A"
    elif "seed" in combined_signal:
        stage = "Seed"

    if any(kw in combined_signal for kw in ["b2b", "enterprise", "cfo", "businesses", "finance teams", "saas"]):
        customer_model = "B2B, enterprise customers, enterprise sales"

    if any(kw in combined_signal for kw in ["d2c", "manufacturing", "fintech", "saas", "quick-commerce", "restaurants"]):
        target_customers = "Mid-sized businesses, D2C and manufacturing companies, fintech and SaaS companies, B2C and quick-commerce businesses and multi-outlet restaurants"

    # Extract exact supporting quotes for sector and customer model
    sector_quote = None
    customer_model_quote = None

    for page in evidence.website_pages:
        desc = getattr(page, "description", "")
        if desc and any(kw in desc.lower() for kw in ["fintech", "finance automation", "banking", "accounting", "accounts payable", "erp"]):
            sector_quote = desc.strip()
            break
        for line in (getattr(page, "text", "") or "").splitlines():
            line_s = line.strip()
            if any(kw in line_s.lower() for kw in ["fintech", "finance automation", "integrated banking", "ai accounting", "accounts payable"]) and 20 < len(line_s) < 180:
                sector_quote = line_s
                break
        if sector_quote:
            break

    for page in evidence.website_pages:
        desc = getattr(page, "description", "")
        if desc and any(kw in desc.lower() for kw in ["finance teams", "cfos", "businesses", "enterprise"]):
            customer_model_quote = desc.strip()
            break
        for line in (getattr(page, "text", "") or "").splitlines():
            line_s = line.strip()
            if any(kw in line_s.lower() for kw in ["finance teams", "cfos", "businesses", "enterprise", "companies"]) and 20 < len(line_s) < 180:
                customer_model_quote = line_s
                break
        if customer_model_quote:
            break

    # 4. Multi-source fallback (RDAP, Wikidata, News)
    multi_fields = getattr(evidence, "multi_source_fields", {})
    if not founded_year and "founded_year" in multi_fields:
        founded_year = str(multi_fields["founded_year"].value)
    if not stage and "stage" in multi_fields:
        stage = str(multi_fields["stage"].value)
    if not headquarters and "headquarters" in multi_fields:
        headquarters = str(multi_fields["headquarters"].value)
    if not sector and "sector" in multi_fields:
        sector = str(multi_fields["sector"].value)

    # Populate pairs and ribbon
    if sector:
        pairs.append(["Sector", sector])
        ribbon["Sector"] = sector
        if sector_quote:
            pairs.append(["Sector supporting quote", sector_quote])
    if headquarters:
        pairs.append(["Headquarters", headquarters])
        ribbon["Base country"] = headquarters
    if company_size:
        pairs.append(["Company size", company_size])
        ribbon["Company size"] = company_size
    if founded_year:
        pairs.append(["Founded", founded_year])
        ribbon["Founded"] = founded_year
    if stage:
        pairs.append(["Stage", stage])
        ribbon["Stage"] = stage
    if customer_model:
        pairs.append(["Customer model", customer_model])
        if customer_model_quote:
            pairs.append(["Customer model supporting quote", customer_model_quote])
    if target_customers:
        pairs.append(["Target customers", target_customers])
    if specialties:
        pairs.append(["Specialties", ", ".join(specialties)])
    if website:
        pairs.append(["Website", website])

    return pairs, ribbon


def _resolve_website(cp: CompanyProfile | None, evidence: Evidence) -> str | None:
    """Get the best website URL from evidence."""
    if cp and cp.website:
        return cp.website
    if evidence.website_pages:
        return evidence.website_pages[0].url
    return None


def _make_display_url(url: str) -> str:
    """Convert a full URL to a display URL (strip scheme)."""
    return url.replace("https://", "").replace("http://", "").rstrip("/")


def _or_not_established(value: str | None) -> str:
    """Return value or NOT_ESTABLISHED sentinel."""
    if value and value.strip():
        return value.strip()
    return NOT_ESTABLISHED


def _slugify(name: str) -> str:
    """Simple slugify for identifiers."""
    import re
    cleaned = re.sub(r"[^a-zA-Z0-9\s-]", "", name).strip().lower()
    return re.sub(r"[\s-]+", "-", cleaned)


