"""Map collected evidence to a complete canonical report JSON tree.

This is a PURE FUNCTION — no I/O, no LLM calls, no side effects.
The output must pass version_gate + schema_validator + ReportImportService.

Canonical JSON contract:
    canonical.meta.canonical_version = "commercial-screen-canonical.2"
    canonical.content.final.meta.schema_version = "vset.screen.v2"
    canonical.content.sections[].blocks = [type, title, ...payload]  (tuple format)
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from typing import Any

from app.domain.entities.discovery import (
    CompanyProfile,
    Evidence,
    EvidenceSource,
    PersonProfile,
    generate_content_fingerprint,
    generate_screen_id,
)


# ── Constants ──────────────────────────────────────────────────────────

CANONICAL_VERSION = "commercial-screen-canonical.2"
SCHEMA_VERSION = "vset.screen.v2"
NOT_ESTABLISHED = "Not established from public sources."
PRODUCT_NAME = "COMMERCIAL_SCREEN"


# ── Public API ─────────────────────────────────────────────────────────

def build_canonical_report(
    evidence: Evidence,
    company_name: str,
    founder_names: list[str],
) -> dict[str, Any]:
    """Build a complete canonical JSON tree from collected evidence.

    Returns a dict that passes ``version_gate`` + ``schema_validator`` and
    can be fed directly to ``ReportImportService.import_report()``.
    """
    now = datetime.now(timezone.utc)
    now_iso = now.isoformat()
    now_date = now.strftime("%Y-%m-%d")
    now_human = now.strftime("%-d %B %Y") if not _is_windows() else now.strftime("%d %B %Y").lstrip("0")

    screen_id = generate_screen_id(company_name)
    report_ref = screen_id.replace("cs_", "")[:12]

    cp = evidence.company_profile
    website = _resolve_website(cp, evidence)

    # ── Sections ───────────────────────────────────────────────────────
    sections = [
        _build_company_section(evidence, company_name, website, now_human),
        _build_team_section(evidence, company_name, founder_names),
        _build_product_section(evidence, company_name),
        _build_validation_section(evidence, company_name),
        _build_market_section(evidence, company_name),
        _build_competition_section(evidence, company_name),
        _build_funding_section(evidence, company_name),
    ]

    # ── Actions (SECTION_REQUEST) ──────────────────────────────────────
    actions = _build_section_actions(sections)

    # ── Action requirements (DD questions + documents) ─────────────────
    action_requirements = _build_action_requirements(company_name, founder_names, evidence)

    # ── Source register ────────────────────────────────────────────────
    source_register = _build_source_register(evidence)

    # ── Report basis ───────────────────────────────────────────────────
    limitations: list[str] = [
        "Some information may be behind authentication walls and could not be retrieved.",
        "This report was generated by an automated discovery process and should be reviewed by a human analyst.",
        "Financial and operational claims have not been independently verified.",
    ]
    linkedin_blocked = False
    for diag in getattr(evidence, "diagnostics", []):
        d_url_lower = diag.url.lower()
        if "linkedin.com" in d_url_lower or diag.url.startswith("linkedin:"):
            if diag.outcome in ("blocked_by_bot_protection", "circuit_breaker_open", "auth_wall") or diag.outcome.startswith("http_error"):
                linkedin_blocked = True

        if diag.outcome == "blocked_by_bot_protection":
            limitations.append(f"Bot protection challenge blocked public retrieval for {diag.url}.")
        elif diag.outcome == "circuit_breaker_open":
            limitations.append(f"Circuit breaker open: skipped public retrieval for {diag.url} to respect rate protection.")
        elif diag.outcome == "auth_wall":
            limitations.append(f"Auth wall blocked public retrieval for {diag.url}.")
        elif diag.outcome.startswith("http_error"):
            limitations.append(f"HTTP error retrieving {diag.url} ({diag.outcome}).")
        elif diag.outcome == "robots_blocked":
            limitations.append(f"Robots.txt disallowed automated retrieval for {diag.url}.")
        elif diag.outcome == "timeout":
            limitations.append(f"Request timed out while retrieving {diag.url}.")
        elif diag.outcome == "empty_text" and not diag.url.startswith("search:"):
            limitations.append(f"No usable text content could be extracted from {diag.url}.")

    if linkedin_blocked:
        limitations.append("LinkedIn could not be retrieved from this server.")

    for w in getattr(evidence, "warnings", []):
        if "LLM enrichment unavailable" in w:
            limitations.append("LLM enrichment unavailable: model not found.")
        elif "auth-walled" in w.lower():
            limitations.append(w)
        elif "linkedin" in w.lower() and "block" in w.lower():
            limitations.append(w)

    # Deduplicate while preserving order
    seen_limits: set[str] = set()
    deduped_limits: list[str] = []
    for lim in limitations:
        if lim not in seen_limits:
            seen_limits.add(lim)
            deduped_limits.append(lim)

    report_basis = {
        "about": (
            f"This report is an independent public-source assessment of {company_name}. "
            "Data was gathered automatically from publicly available web pages. "
            "No non-public or confidential information was used."
        ),
        "limitations": deduped_limits,
        "research_window": {
            "from": now_date,
            "to": now_date,
        },
    }

    # ── Concerns & conflicts ──────────────────────────────────────────
    concerns_conflicts = {
        "concerns": [],
        "conflicts": [],
        "message": "No material concerns or conflicts were identified during this automated screen.",
    }

    # ── Assemble content ──────────────────────────────────────────────
    content: dict[str, Any] = {
        "cover": {
            "company_name": company_name,
            "report_reference": report_ref,
            "research_cutoff": now_human,
            "website": website or "",
        },
        "sections": sections,
        "actions": actions,
        "action_requirements": action_requirements,
        "body_gate": {},
        "final": {
            "meta": {
                "schema_version": SCHEMA_VERSION,
                "as_of_date": now_date,
            },
            "evidence_register": source_register,
            "report_basis": report_basis,
            "concerns_conflicts": concerns_conflicts,
        },
    }

    # ── Fingerprint ───────────────────────────────────────────────────
    content_str = json.dumps(content, sort_keys=True, default=str)
    fingerprint = generate_content_fingerprint(content_str)

    # ── Canonical meta ────────────────────────────────────────────────
    canonical_meta: dict[str, Any] = {
        "canonical_screen_id": screen_id,
        "canonical_version": CANONICAL_VERSION,
        "company_name": company_name,
        "final_fingerprint": fingerprint,
        "canonical_content_fingerprint": fingerprint,
        "website": website,
        "report_id": f"discovery-{_slugify(company_name)}",
        "research_cutoff": now_date,
        "generated_at": now_iso,
        "version": "V1",
        "audience": "FOUNDER",
    }

    # Also write fingerprint into final.meta
    content["final"]["meta"]["final_fingerprint"] = fingerprint

    # ── Top-level meta ────────────────────────────────────────────────
    top_meta: dict[str, Any] = {
        "audience": "FOUNDER",
        "company_name": company_name,
        "website": website or "",
        "canonical_screen_id": screen_id,
        "canonical_content_fingerprint": fingerprint,
        "generated_at": now_iso,
        "research_cutoff": now_date,
        "report_id": f"discovery-{_slugify(company_name)}",
        "product": PRODUCT_NAME,
        "version": "V1",
    }

    # ── Presentation ──────────────────────────────────────────────────
    slug = _slugify(company_name)
    presentation: dict[str, Any] = {
        "audience_label": "Founder Screen",
        "action_section_title": "Investor questions & information to prepare",
        "action_intro": (
            "Part A lists the questions an investor would likely ask during a first "
            "screening call. Part B lists supporting documents and data to prepare."
        ),
        "action_part_a_title": "A. Questions to prepare for",
        "action_part_b_title": "B. Supporting documents & data to prepare",
        "about_screen_audience_text": (
            f"This report was prepared for the founding team of {company_name} "
            "to help them prepare for investor screening conversations."
        ),
        "filename_stem": f"{slug}_founder_screen",
        "pdf_title": f"{company_name} — Startup Screening Report",
        "pdf_subject": f"Startup screening report for {company_name}",
        "section_action_heading": "Information to prepare",
    }

    return {
        "canonical": {
            "meta": canonical_meta,
            "content": content,
        },
        "meta": top_meta,
        "presentation": presentation,
    }


# ── Section builders ───────────────────────────────────────────────────

def _build_company_section(
    evidence: Evidence, company_name: str, website: str | None, cutoff: str,
) -> dict[str, Any]:
    """Section 1: Key facts & context."""
    overview_text = _extract_merged_company_overview(evidence, company_name)
    kv_pairs, ribbon_dict = _extract_merged_company_profile(evidence, company_name, website)

    products = _extract_products_rules(evidence.website_pages)

    # Ribbon (key facts shown in the section header)
    ribbon: list[list[str]] = []
    for key in ["Base country", "Founded", "Sector", "Company size", "Stage"]:
        if key in ribbon_dict:
            ribbon.append([key, ribbon_dict[key]])

    blocks: list[list[Any]] = [
        ["para", "What the company does", overview_text],
        ["kv", "Company profile", kv_pairs],
    ]

    if products:
        blocks.append([
            "olist",
            "Products & services",
            [f"{p['name']} - {p['description']}" for p in products],
        ])

    # Website-sourced about text if available and distinct from overview
    about_text = _extract_about_from_pages(evidence.website_pages)
    if about_text and about_text != overview_text and overview_text != NOT_ESTABLISHED:
        blocks.append(["para", "About (from website)", about_text])

    # GAPS: REAL MISSING FIELDS ONLY! Metadata and notices are never gaps.
    field_keys = {k for k, _ in kv_pairs}
    gaps: list[str] = []
    if overview_text == NOT_ESTABLISHED:
        gaps.append("Company overview and core business description not established from public sources.")
    if "Sector" not in field_keys:
        gaps.append("Industry sector not established from public sources.")
    if "Headquarters" not in field_keys:
        gaps.append("Headquarters and operating jurisdiction not established.")
    if "Founded" not in field_keys:
        gaps.append("Founding date or year not established.")
    if "Company size" not in field_keys:
        gaps.append("Team and company size not established.")

    if gaps:
        blocks.append(["list", "Information gaps", gaps])

    return {
        "key": "company",
        "title": "Key facts & context",
        "ribbon": ribbon,
        "blocks": blocks,
    }


def _build_team_section(
    evidence: Evidence, company_name: str, founder_names: list[str],
) -> dict[str, Any]:
    """Section 2: Founder & team."""
    founder_cards = _build_founder_cards(evidence, founder_names, company_name)

    kv_pairs: list[list[str]] = [
        ["Founding team", str(len(founder_names))],
    ]

    blocks: list[list[Any]] = [
        ["kv", None, kv_pairs],
    ]

    if founder_cards:
        blocks.append(["cards", "Founder details", founder_cards])
    else:
        blocks.append(["para", "Founder details", NOT_ESTABLISHED])

    # Real gaps only: check which founders had incomplete background
    gaps: list[str] = []
    for card in founder_cards:
        name = card.get("name", "")
        lines = card.get("lines", [])
        has_history = any(l[0] in ("Experience", "Current role") for l in lines)
        if not has_history:
            gaps.append(f"Full career history and background for {name} not established from public sources.")

    if len(founder_names) > 0 and not any(p.experience for p in evidence.founder_profiles):
        gaps.append("Executive team composition beyond founders not established.")

    if gaps:
        deduped_gaps = list(dict.fromkeys(gaps))
        blocks.append(["list", "Information gaps", deduped_gaps])

    return {
        "key": "team",
        "title": "Founder & team",
        "ribbon": [],
        "blocks": blocks,
    }


def _extract_product_from_pages(pages: list[Any]) -> str | None:
    """Extract product overview from website pages."""
    for page in pages:
        url_lower = getattr(page, "url", "").lower()
        title_lower = getattr(page, "title", "").lower()
        if any(k in url_lower or k in title_lower for k in ("product", "platform", "solution", "feature", "technology", "service", "system")):
            text = getattr(page, "text", "")
            if text and len(text.strip()) > 30:
                lines = [l.strip() for l in text.strip().split("\n") if len(l.strip()) > 25]
                if lines:
                    return " ".join(lines[:4])[:600]
            if page.description and len(page.description.strip()) > 10:
                return page.description.strip()
    return None


def _build_product_section(evidence: Evidence, company_name: str) -> dict[str, Any]:
    """Section 3: Product & technology."""
    products = _extract_products_rules(evidence.website_pages)
    product_text = _extract_product_from_pages(evidence.website_pages)
    if not product_text and evidence.website_pages:
        for p in evidence.website_pages:
            if p.description and any(kw in p.description.lower() for kw in ["product", "platform", "app", "service", "system", "technology", "smart"]):
                product_text = p.description
                break

    overview = _or_not_established(product_text)
    blocks: list[list[Any]] = [
        ["para", "Product overview", overview],
    ]

    if products:
        blocks.append([
            "olist",
            "Products & services",
            [f"{p['name']} - {p['description']}" for p in products],
        ])

    gaps: list[str] = []
    if overview == NOT_ESTABLISHED and not products:
        gaps.append("Product specifications and architecture not established from public sources.")
    gaps.append("Intellectual property and proprietary patents not established.")

    blocks.append(["list", "Information gaps", gaps])

    return {
        "key": "product",
        "title": "Product & technology",
        "ribbon": [],
        "blocks": blocks,
    }


def _build_validation_section(evidence: Evidence, company_name: str) -> dict[str, Any]:
    """Section 4: Validation & market signals."""
    customers = _extract_customers_rules(evidence.website_pages)
    blocks: list[list[Any]] = []

    if customers:
        client_names = [c["name"] for c in customers[:6]]
        blocks.append([
            "para",
            "Validation status",
            f"{company_name} demonstrates commercial validation with deployments and case studies across enterprise and mid-market customers including {', '.join(client_names)}.",
        ])
        blocks.append([
            "list",
            "Named customer case studies & signals",
            [f"{c['name']} ({c['url']}) — quote: '{c['quote']}'" for c in customers[:8]],
        ])
    else:
        blocks.append(["para", "Validation status", NOT_ESTABLISHED])

    marketing = _extract_marketing_claims(evidence.website_pages)
    if marketing:
        blocks.append([
            "list",
            "Marketing metrics & claims (company-stated, unverified)",
            [f"\"{m['claim']}\" (source: {m['url']}) — company-stated, unverified" for m in marketing],
        ])

    gaps: list[str] = []
    if not customers:
        gaps.append("Customer traction and revenue not established from public sources.")
    gaps.append("Partnership and pilot details not established.")

    blocks.append(["list", "Information gaps", gaps])

    return {
        "key": "validation",
        "title": "Validation & market signals",
        "ribbon": [],
        "blocks": blocks,
    }


