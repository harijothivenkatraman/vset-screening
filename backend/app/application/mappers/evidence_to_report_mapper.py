# ── Source register ────────────────────────────────────────────────────

def _build_source_register(evidence: Evidence) -> dict[str, Any]:
    """Build the evidence_register from collected sources."""
    sources_list: list[dict[str, Any]] = []
    for src in evidence.sources:
        sources_list.append({
            "source_id": src.source_id,
            "title": src.title,
            "publisher": src.publisher,
            "published_date": src.published_date,
            "display_url": _make_display_url(src.url),
            "canonical_url": src.url,
            "source_type": src.source_type,
            "ownership_class": "UNRESOLVED",
            "document_key": f"url:{src.url}",
            "original_urls": [src.url],
            "versions": [{"content_fingerprint": None, "retrieved_date": src.retrieved_at, "version_id": None}],
        })

    return {
        "sources": sources_list,
        "claims": [],
        "profile_by_domain": {},
    }


# ── Founder card helpers ───────────────────────────────────────────────

def _build_founder_cards(
    evidence: Evidence, founder_names: list[str],
) -> list[dict[str, Any]]:
    """Build founder card dicts matching the existing FounderCard shape."""
    cards: list[dict[str, Any]] = []

    # Build a lookup: lowercased name fragments → profile
    profile_map: dict[str, PersonProfile] = {}
    for p in evidence.founder_profiles:
        if p.name:
            profile_map[p.name.lower()] = p

    for name in founder_names:
        profile = _find_profile(name, profile_map)

        lines: list[list[str]] = []
        fit = ""

        if profile:
            # Education line
            edu_parts = [
                f"{e.get('degree', '')} — {e.get('institution', '')} ({e.get('year', '')})"
                for e in profile.education
                if e.get("institution")
            ]
            if edu_parts:
                lines.append(["Education", "; ".join(edu_parts)])

            # Experience line
            exp_parts = [
                f"{e.get('title', '')} at {e.get('company', '')} ({e.get('duration', '')})"
                for e in profile.experience
                if e.get("company")
            ]
            if exp_parts:
                lines.append(["Experience", "; ".join(exp_parts)])
            elif profile.headline:
                lines.append(["Current role", profile.headline])

            # Fit summary
            if profile.summary:
                fit = profile.summary[:300]
            elif profile.headline:
                fit = f"{name}'s background as {profile.headline} is relevant to {name}'s role."

            role = profile.headline or "Co-founder"
        else:
            lines.append(["Profile", "Not retrievable from public sources."])
            fit = "Founder profile could not be retrieved from public sources."
            role = "Co-founder"

        cards.append({
            "name": name,
            "role": role,
            "lines": lines,
            "fit": fit,
        })

    return cards


def _find_profile(name: str, profile_map: dict[str, PersonProfile]) -> PersonProfile | None:
    """Fuzzy match a founder name to a scraped profile."""
    name_lower = name.lower()
    # Exact match
    if name_lower in profile_map:
        return profile_map[name_lower]
    # Partial match (last name)
    parts = name_lower.split()
    for key, profile in profile_map.items():
        if any(part in key for part in parts if len(part) > 2):
            return profile
    return None


# ── Text extraction helpers ────────────────────────────────────────────

def _extract_about_from_pages(pages: list[Any]) -> str | None:
    """Extract about text from website pages."""
    for page in pages:
        if hasattr(page, "text") and page.text:
            text = page.text.strip()
            if len(text) > 50:
                return text[:1500]
    return None


def _extract_product_from_pages(pages: list[Any]) -> str | None:
    """Extract product info from website pages."""
    for page in pages:
        url = getattr(page, "url", "")
        if "product" in url.lower() or "service" in url.lower():
            text = getattr(page, "text", "").strip()
            if text:
                return text[:1500]
    return None


def _extract_funding_from_news(articles: list[Any]) -> str | None:
    """Extract funding mentions from news articles."""
    for article in articles:
        text = getattr(article, "text", "").strip()
        title = getattr(article, "title", "").strip()
        combined = f"{title} {text}".lower()
        if any(kw in combined for kw in ["funding", "raised", "investment", "seed", "series"]):
            return text[:1500] if text else title
    return None


# ── Utility helpers ────────────────────────────────────────────────────

def _company_profile_kv(
    cp: CompanyProfile | None, company_name: str, website: str | None,
) -> list[list[str]]:
    """Build KV pairs for the company profile block."""
    pairs: list[list[str]] = [
        ["Legal name", company_name],
    ]
    if cp:
        if cp.industry:
            pairs.append(["Sector", cp.industry])
        if cp.headquarters:
            pairs.append(["Headquarters", cp.headquarters])
        if cp.company_size:
            pairs.append(["Company size", cp.company_size])
        if cp.founded_year:
            pairs.append(["Founded", cp.founded_year])
        if cp.specialties:
            pairs.append(["Specialties", ", ".join(cp.specialties)])
    if website:
        pairs.append(["Website", website])

    return pairs


def _resolve_website(cp: CompanyProfile | None, evidence: Evidence) -> str | None:
    """Get the best website URL from evidence."""
    if cp and cp.website:
        return cp.website
    if evidence.website_pages:
        return evidence.website_pages[0].url
    return None


def _make_display_url(url: str) -> str:
    """Convert a full URL to a display URL (strip scheme)."""
    return url.replace("https://", "").replace("http://", "").rstrip("/")


def _or_not_established(value: str | None) -> str:
    """Return value or NOT_ESTABLISHED sentinel."""
    if value and value.strip():
        return value.strip()
    return NOT_ESTABLISHED


def _slugify(name: str) -> str:
    """Simple slugify for identifiers."""
    import re
    cleaned = re.sub(r"[^a-zA-Z0-9\s-]", "", name).strip().lower()
    return re.sub(r"[\s-]+", "-", cleaned)


def _is_windows() -> bool:
    """Check if running on Windows (affects strftime)."""
    import sys
    return sys.platform == "win32"
