# ── Actions / DD builders ─────────────────────────────────────────────

def _build_section_actions(sections: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Generate SECTION_REQUEST action items from gap lists."""
    actions: list[dict[str, Any]] = []
    idx = 0
    for section in sections:
        for block in section.get("blocks", []):
            if isinstance(block, list) and block[0] == "list" and "Information gaps" in str(block[1]):
                for item_text in block[2] if len(block) > 2 and isinstance(block[2], list) else []:
                    actions.append({
                        "action_id": f"act_disc_{idx:04d}",
                        "kind": "SECTION_REQUEST",
                        "where": section["title"],
                        "text": item_text,
                        "why": "Not established from public sources.",
                        "key": section["key"],
                        "semantic_key": f"{section['key']}.gap.{idx}",
                    })
                    idx += 1
    return actions


